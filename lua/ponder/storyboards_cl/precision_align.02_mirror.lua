local sb = Ponder.API.NewStoryboard("precision_align", "tutorials", "mirror")
sb:WithMenuName("Planes and mirroring")
sb:WithPlaybackName("Planes and mirroring")
sb:WithModelIcon("models/hunter/plates/plate1x1.mdl")
sb:WithDescription("Define a plane and mirror a prop across it.")
sb:SetPrimaryLanguage("en")
sb:WithIndexOrder(2) -- Ponder lists the highest first

local Half, ToolPos = 23.725, Vector(90, -90, 90)
local Plate = "models/hunter/plates/plate1x1.mdl"
local RefPos = Vector(0, 0, 70)
local PlatePos, PlateAng = Vector(90, 0, 70), Angle(20, 0, 0)
local HitOrigin, HitNormal = RefPos + Vector(0, 0, Half), Vector(0, 0, 1) -- Where the first click lands, on top of the cube
local SideHit, PlaneNormal = RefPos + Vector(Half, 0, 0), Vector(1, 0, 0) -- The second click lands on its side
local PlaneSize = 90
local PlateColor = Color(120, 160, 220)

---------------------------------------------
-- Defining a plane
---------------------------------------------
local c = sb:Chapter("Defining a plane")
c:AddInstruction("MoveCameraLookAt", {Target = Vector(0, 0, 60), Distance = 1400, Angle = 35, Height = 450, Length = 0.6})
c:AddInstruction("PlaceModel", {Name = "ref", Model = "models/hunter/blocks/cube1x1x1.mdl", Position = RefPos, Length = 0})
c:AddInstruction("ColorModel", {Target = "ref", Color = Color(230, 170, 60), Length = 0})
c:AddInstruction("PlaceModel", {Name = "plate", Model = Plate, Position = PlatePos, Angles = PlateAng, Length = 0})
c:AddInstruction("ColorModel", {Target = "plate", Color = PlateColor, Length = 0})
c:AddInstruction("ShowToolgun", {Tool = "precision_align", Position = ToolPos, Length = 0.375})
c:AddInstruction("Caption", {Text = "A plane is a flat surface with an origin and a direction. We will mirror the blue plate across an upright plane through the orange cube.", FadeInOutTime = 0.225, TextLength = 5})
c:AddDelay(5.5)
c:AddInstruction("PAToolMenu", {Name = "menu", Mode = "Plane - Hitpos + Hitnormal"})
c:AddDelay(0.5)
c:AddInstruction("Caption", {Text = "With Plane - Hitpos + Hitnormal, left click a surface. The plane sits where you hit and faces away from the surface.", FadeInOutTime = 0.225, TextLength = 5})
c:AddDelay(1)
c:AddInstruction("PAClick", {Button = "Left Click", Position = HitOrigin})
c:AddInstruction("PAPlane", {Name = "plane", Origin = HitOrigin, Normal = HitNormal, Size = PlaneSize, Label = "1"})
c:AddDelay(3.5)
c:AddInstruction("Caption", {Text = "That plane is flat, but we want an upright one. Plane - Hitnormal keeps the origin and only changes the direction.", FadeInOutTime = 0.225, TextLength = 5})
c:AddDelay(1)
c:AddInstruction("PAMenuMode", {Name = "menu", Mode = "Plane - Hitnormal"})
c:AddDelay(4.5)
c:AddInstruction("Caption", {Text = "Left click the side of the cube. Its surface faces sideways, so the plane turns to face sideways too.", FadeInOutTime = 0.225, TextLength = 4.5})
c:AddDelay(1)
c:AddInstruction("PAClick", {Button = "Left Click", Position = SideHit})
c:AddInstruction("PAPlane", {Name = "plane", Origin = HitOrigin, Normal = PlaneNormal, Size = PlaneSize, Label = "1"})
c:AddDelay(3.5)

---------------------------------------------
-- Mirroring the prop
---------------------------------------------
c = sb:Chapter("Mirroring the prop")
c:AddInstruction("RemovePanel", {Name = "menu", Length = 0.3})
c:AddInstruction("MoveCameraLookAt", {Target = Vector(0, 0, 70), Distance = 1400, Angle = 0, Height = 70, Length = 1.5})
c:AddInstruction("Caption", {Text = "Viewed along the plane, the blue plate sits on one side of it. Right click the plate to select it.", FadeInOutTime = 0.225, TextLength = 4})
c:AddDelay(2)
c:AddInstruction("PAClick", {Button = "Right Click", Position = PlatePos})
c:AddInstruction("ColorModel", {Target = "plate", Color = Color(150, 200, 255), Length = 0.3})
c:AddDelay(2.5)
c:AddInstruction("Caption", {Text = "Press Reload to open the manipulation panel.", FadeInOutTime = 0.225, TextLength = 3})
c:AddDelay(c:AddInstruction("KeyPress", {Name = "reload", Key = "R", Position = Vector(0.5, 0.27, 0)}).PressedAt)
c:AddInstruction("PAManipulationPanel", {Name = "manip"})
c:AddDelay(3.5)
c:AddInstruction("Caption", {Text = "On the Rotation Functions tab, pick Mirror Across Plane and select the plane to mirror across.", FadeInOutTime = 0.225, TextLength = 5})
c:AddDelay(1)
c:AddDelay(c:AddInstruction("PAMenuPress", {Name = "manip", Within = "rotation_functions_tab", Text = "Mirror Across Plane", Activate = true, Length = 1}).Length)
c:AddInstruction("PAMenuSelect", {Name = "manip", Within = "rotation_functions_tab", List = "list_plane_1", Line = 1})
c:AddDelay(5)
c:AddInstruction("Caption", {Text = "Hold Shift while pressing the button to keep the original and stack a mirrored copy.", FadeInOutTime = 0.225, TextLength = 4.5})
c:AddDelay(1)
c:AddInstruction("PAMenuEnable", {Name = "manip", Within = "rotation_functions_tab", Text = "Rotate Entity"})
local shift = c:AddInstruction("KeyPress", {Name = "shift", Key = "Shift", Position = Vector(0.5, 0.27, 0)})
c:AddDelay(shift.PressedAt)
local press = c:AddInstruction("PAMenuPress", {Name = "manip", Within = "rotation_functions_tab", Text = "Rotate Entity", Label = "(SHIFT) Stack Entity", Length = 1.2})
c:AddDelay(press.Length)
shift:ReleaseAt(c.Time)
c:AddInstruction("RemovePanel", {Name = "manip", Length = 0.3})
c:AddDelay(0.4)
c:AddInstruction("PAMirrorModel", {Target = "plate", Origin = HitOrigin, Normal = PlaneNormal, Copy = "mirrored", CopyColor = PlateColor})
c:AddInstruction("ColorModel", {Target = "plate", Color = PlateColor, Length = 0.3})
c:AddDelay(2.3)
c:AddInstruction("Caption", {Text = "The original stays and a copy is made on the other side of the plane, tilted the opposite way.", FadeInOutTime = 0.225, TextLength = 5})
c:AddDelay(5.5)
c:AddInstruction("HideToolgun", {Length = 0.375})
c:AddDelay(0.375)
